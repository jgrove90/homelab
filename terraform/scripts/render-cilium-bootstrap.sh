#!/usr/bin/env bash
# Renders the Cilium bootstrap manifest that Talos applies via cluster.inlineManifests
# (see talos_config.tf and docs/architecture/decisions/0002-*.md).
#
# Single source of truth: chart version + values come from the Flux HelmRelease, so the
# bootstrap manifest cannot drift from what Flux manages.
#
# Secret objects are stripped: the chart generates a CA and Hubble TLS keys at render time,
# and private keys must not live in Git or Terraform state. Cilium starts fine without them
# (the agent's hubble-server-certs volume is optional); Flux's HelmRelease creates them.
#
# Re-run this whenever the Cilium chart version or values change in the HelmRelease.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
HR="$ROOT/kubernetes/clusters/home/2-infra/cilium/helm-release.yaml"
OUT="$ROOT/terraform/manifests/cilium-bootstrap.yaml"

command -v helm >/dev/null || { echo "helm is required" >&2; exit 1; }
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT

version="$(python3 -c 'import sys,yaml;print(yaml.safe_load(open(sys.argv[1]))["spec"]["chart"]["spec"]["version"])' "$HR")"
python3 -c 'import sys,yaml;yaml.safe_dump(yaml.safe_load(open(sys.argv[1]))["spec"]["values"],open(sys.argv[2],"w"))' "$HR" "$tmp/values.yaml"

helm repo add cilium https://helm.cilium.io >/dev/null 2>&1 || true
helm template cilium cilium/cilium --version "$version" --namespace kube-system -f "$tmp/values.yaml" > "$tmp/rendered.yaml"

python3 - "$tmp/rendered.yaml" "$OUT" "$version" <<'PY'
import sys, yaml
src, out, version = sys.argv[1:4]
docs = [d for d in yaml.safe_load_all(open(src)) if d and d.get("kind") != "Secret"]
with open(out, "w") as f:
    f.write(f"# GENERATED by terraform/scripts/render-cilium-bootstrap.sh - do not edit by hand.\n")
    f.write(f"# Cilium chart {version}, values from the Flux HelmRelease. Secrets intentionally omitted.\n")
    yaml.safe_dump_all(docs, f, sort_keys=False)
print(f"wrote {out} (chart {version}, {len(docs)} objects)")
PY
